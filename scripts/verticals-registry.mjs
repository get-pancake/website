#!/usr/bin/env node
// scripts/verticals-registry.mjs — regenerates lib/verticals/data/index.ts from
// every lib/verticals/data/<slug>.ts that exports `const x: VerticalConfig`.
//
//   node scripts/verticals-registry.mjs          write the index (idempotent)
//   node scripts/verticals-registry.mjs --check  exit 1 if the index is stale
//
// Why generated: 40 configs, written by several people (and agents) at once.
// A hand-kept import list drifts; a runtime glob (require.context / fs) breaks
// static generation and tree-shaking. The generator is the one place that
// knows the folder, and `--check` is the CI/pre-PR gate for a forgotten run.
//
// Robustness while configs are being written concurrently: a file whose
// source does not parse (TypeScript syntactic diagnostics) or that has no
// `export const <name>: VerticalConfig` is SKIPPED with a warning instead of
// breaking every /for page (and the nav, which lists the verticals) in dev.
// Shape/copy rules are NOT checked here: that is validateVerticals(), which
// logs in dev and throws in production builds (lib/verticals/index.ts).

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = join(root, "lib/verticals/data");
const out = join(dataDir, "index.ts");
const check = process.argv.includes("--check");

let ts = null;
try {
  ts = createRequire(join(root, "package.json"))("typescript");
} catch {
  console.warn("[verticals-registry] typescript not found — skipping the syntax pre-check");
}

const files = readdirSync(dataDir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.startsWith("_") && !f.endsWith(".d.ts"))
  .sort();

const entries = [];
const skipped = [];
for (const file of files) {
  const src = readFileSync(join(dataDir, file), "utf8");
  const m = src.match(/export\s+const\s+([A-Za-z_$][\w$]*)\s*:\s*VerticalConfig\b/);
  if (!m) {
    skipped.push(`${file}: no \`export const <name>: VerticalConfig\``);
    continue;
  }
  if (ts) {
    const res = ts.transpileModule(src, { reportDiagnostics: true, fileName: file, compilerOptions: { target: ts.ScriptTarget.ES2020 } });
    const diags = (res.diagnostics ?? []).filter((d) => d.category === ts.DiagnosticCategory.Error);
    if (diags.length) {
      const d = diags[0];
      const where = d.file && d.start != null ? d.file.getLineAndCharacterOfPosition(d.start) : null;
      skipped.push(`${file}: syntax error${where ? ` at ${where.line + 1}:${where.character + 1}` : ""} — ${ts.flattenDiagnosticMessageText(d.messageText, " ")}`);
      continue;
    }
  }
  const slug = file.replace(/\.ts$/, "");
  entries.push({ file, slug, name: m[1] });
}

// Duplicate export names would collide in the generated import list.
const names = new Map();
for (const e of entries) {
  if (names.has(e.name)) {
    skipped.push(`${e.file}: export name "${e.name}" already used by ${names.get(e.name)}`);
    e.dup = true;
  } else names.set(e.name, e.file);
}
const ok = entries.filter((e) => !e.dup);

const body = `// lib/verticals/data/index.ts — GENERATED by scripts/verticals-registry.mjs. Do not edit.
// Re-run \`node scripts/verticals-registry.mjs\` after adding, renaming or removing a config.
// Order = file name order (deterministic); hub and nav order is decided in lib/verticals/index.ts.
import type { VerticalConfig } from "../types";
${ok.map((e) => `import { ${e.name} } from "./${e.slug}";`).join("\n")}

export const ALL_VERTICALS: VerticalConfig[] = [
${ok.map((e) => `  ${e.name},`).join("\n")}
];
`;

for (const s of skipped) console.warn(`[verticals-registry] skipped ${s}`);

const prev = existsSync(out) ? readFileSync(out, "utf8") : "";
if (check) {
  if (prev !== body) {
    console.error(`[verticals-registry] lib/verticals/data/index.ts is stale (${ok.length} configs on disk). Run: node scripts/verticals-registry.mjs`);
    process.exit(1);
  }
  console.log(`[verticals-registry] up to date: ${ok.length} config(s)`);
  process.exit(skipped.length ? 1 : 0);
}
if (prev !== body) writeFileSync(out, body);
console.log(`[verticals-registry] ${prev === body ? "unchanged" : "wrote"} lib/verticals/data/index.ts: ${ok.length} config(s)${skipped.length ? `, ${skipped.length} skipped` : ""}`);
