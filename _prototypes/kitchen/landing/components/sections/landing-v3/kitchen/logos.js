/** the logo as an inline SVG string */
export function logoSvg(key) {
  const l = LOGOS[key];
  return (
    '<svg viewBox="' + l.box + '" aria-hidden="true" focusable="false">' +
    l.paths.map(([fill, d]) => '<path fill="' + fill + '" d="' + d + '"/>').join("") +
    "</svg>"
  );
}

/** draws the logo on a canvas, fitted in the square (x, y, size) */
export function drawLogo(g, key, x, y, size) {
  const l = LOGOS[key];
  const [bx, by, bw, bh] = l.box.split(" ").map(Number);
  const k = size / Math.max(bw, bh);
  g.save();
  g.translate(x + (size - bw * k) / 2 - bx * k, y + (size - bh * k) / 2 - by * k);
  g.scale(k, k);
  for (const [fill, d] of l.paths) {
    g.fillStyle = fill;
    g.fill(new Path2D(d));
  }
  g.restore();
}
